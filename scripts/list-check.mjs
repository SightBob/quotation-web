import { TEST_EMAIL, TEST_PASSWORD } from "./_creds.mjs";
import puppeteer from "puppeteer-core";
const BASE = "http://localhost:3000";
const browser = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage();
await page.setViewport({ width: 1400, height: 800, deviceScaleFactor: 1.25 });
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
const wait = (ms) => new Promise(r => setTimeout(r, ms));
await page.goto(`${BASE}/login`, { waitUntil: "domcontentloaded" });
await page.waitForSelector('input[type="email"]');
await wait(2000);
await page.type('input[type="email"]', TEST_EMAIL);
await page.type('input[type="password"]', TEST_PASSWORD);
await Promise.all([page.waitForNavigation({waitUntil:"domcontentloaded"}).catch(()=>{}), page.click('button[type="submit"]')]);
await wait(1800);
await page.screenshot({ path: process.env.TEMP + "\\opencode\\list-latest.png" });
const linkText = await page.evaluate(() => [...document.querySelectorAll("a")].map(a=>a.textContent.trim()).find(t=>t.includes("แสดง")));
console.log("toggle link:", linkText);
await page.evaluate(() => [...document.querySelectorAll("a")].find(a=>a.textContent.includes("แสดงทุกฉบับ"))?.click());
await wait(1500);
console.log("url after toggle:", page.url());
const rows = await page.evaluate(() => document.querySelectorAll("tbody tr").length);
console.log("rows:", rows);
await page.screenshot({ path: process.env.TEMP + "\\opencode\\list-all.png" });
console.log("page errors:", errs.length ? errs : "none");
await browser.close();
